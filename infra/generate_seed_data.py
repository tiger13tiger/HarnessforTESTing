"""Generates infra/seed_schema.sql (1000 raw_sales rows, ~58 store_promotions
rows across 50 stores) and the matching golden figures for
tests/golden_fact_sales.example.yaml -- computed from the generated data, not
hand-picked, so they're exactly right for whatever this script produces.

Deterministic (fixed seed): re-running it regenerates the identical data and
figures. Run it again only if you want to change the dataset shape; it
overwrites both files.
"""
import random
from collections import defaultdict
from pathlib import Path

random.seed(42)

CATEGORIES = ["Electronics", "Groceries", "Apparel", "Home", "Toys"]
STORE_COUNT = 50
ROW_COUNT = 1000
# These stores get a second (duplicate) promotion row -- what the planted
# fan-out bug in sp_refresh_fact_sales.example.sql doubles up on.
MULTI_PROMO_STORES = {1, 5, 10, 15, 20, 25, 30, 35}

REPO_ROOT = Path(__file__).resolve().parent.parent

# ---- generate raw_sales -----------------------------------------------
sales_rows = []
for sale_id in range(1, ROW_COUNT + 1):
    store_id = random.randint(1, STORE_COUNT)
    category = random.choice(CATEGORIES)
    revenue = round(random.uniform(10.0, 999.99), 2)
    sales_rows.append((store_id, category, revenue))

# ---- generate store_promotions -----------------------------------------
promo_rows = []
for store_id in range(1, STORE_COUNT + 1):
    promo_rows.append((store_id, f"Promo {store_id}-A"))
    if store_id in MULTI_PROMO_STORES:
        promo_rows.append((store_id, f"Promo {store_id}-B"))

# ---- compute correct (golden) per-category totals ----------------------
correct = defaultdict(lambda: {"revenue": 0.0, "txn_count": 0})
for store_id, category, revenue in sales_rows:
    correct[category]["revenue"] += revenue
    correct[category]["txn_count"] += 1

# ---- compute what the BUGGY procedure would actually produce, for the
# generation script's own sanity check (not written to the golden file --
# golden always holds the correct answer) -----------------------------
promo_count_by_store = defaultdict(int)
for store_id, _ in promo_rows:
    promo_count_by_store[store_id] += 1

buggy = defaultdict(lambda: {"revenue": 0.0, "txn_count": 0})
for store_id, category, revenue in sales_rows:
    fan_out = promo_count_by_store[store_id]
    buggy[category]["revenue"] += revenue * fan_out
    buggy[category]["txn_count"] += fan_out

# ---- write infra/seed_schema.sql ---------------------------------------
def sql_values_batches(rows, formatter, batch_size=500):
    batches = []
    for i in range(0, len(rows), batch_size):
        batch = rows[i:i + batch_size]
        batches.append(",\n".join(formatter(r) for r in batch))
    return batches

sales_batches = sql_values_batches(
    sales_rows, lambda r: f"    ({r[0]}, '{r[1]}', {r[2]:.2f})"
)
promo_batches = sql_values_batches(
    promo_rows, lambda r: f"    ({r[0]}, '{r[1]}')"
)

lines = [
    "-- GENERATED by infra/generate_seed_data.py -- do not hand-edit, regenerate instead.",
    "-- Schema + seed data for dbo.raw_sales, dbo.store_promotions, dbo.fact_sales.",
    "-- Run this once against EACH database (dev and uat). Destructive by design",
    "-- (drops and recreates the three tables) -- only run it against these",
    "-- throwaway test databases, never anything with real data.",
    "--",
    f"-- {ROW_COUNT} raw_sales rows across {STORE_COUNT} stores and {len(CATEGORIES)} categories.",
    f"-- Stores {sorted(MULTI_PROMO_STORES)} have a SECOND promotion row -- that's what",
    "-- the planted fan-out join in sp_refresh_fact_sales.example.sql doubles up on.",
    "-- The correct (golden) per-category totals are computed straight from this data",
    "-- by infra/generate_seed_data.py and written into",
    "-- tests/golden_fact_sales.example.yaml -- not hand-picked.",
    "",
    "IF OBJECT_ID('dbo.raw_sales', 'U') IS NOT NULL DROP TABLE dbo.raw_sales;",
    "IF OBJECT_ID('dbo.store_promotions', 'U') IS NOT NULL DROP TABLE dbo.store_promotions;",
    "IF OBJECT_ID('dbo.fact_sales', 'U') IS NOT NULL DROP TABLE dbo.fact_sales;",
    "GO",
    "",
    "CREATE TABLE dbo.raw_sales (",
    "    sale_id INT IDENTITY PRIMARY KEY,",
    "    store_id INT NOT NULL,",
    "    product_category VARCHAR(50) NOT NULL,",
    "    revenue DECIMAL(12,2) NOT NULL",
    ");",
    "",
    "CREATE TABLE dbo.store_promotions (",
    "    promotion_id INT IDENTITY PRIMARY KEY,",
    "    store_id INT NOT NULL,",
    "    promotion_name VARCHAR(100) NOT NULL",
    ");",
    "",
    "CREATE TABLE dbo.fact_sales (",
    "    product_category VARCHAR(50) NOT NULL,",
    "    revenue DECIMAL(12,2) NOT NULL,",
    "    txn_count INT NOT NULL",
    ");",
    "GO",
    "",
]

for batch in sales_batches:
    lines.append("INSERT INTO dbo.raw_sales (store_id, product_category, revenue) VALUES")
    lines.append(batch + ";")
    lines.append("")

for batch in promo_batches:
    lines.append("INSERT INTO dbo.store_promotions (store_id, promotion_name) VALUES")
    lines.append(batch + ";")
    lines.append("")

lines.append("GO")
lines.append("")
lines.append("-- Correct (golden) per-category totals, computed by this script:")
for category in CATEGORIES:
    c = correct[category]
    b = buggy[category]
    lines.append(
        f"--   {category}: revenue={c['revenue']:.2f} txn_count={c['txn_count']}"
        f"  (buggy procedure would produce revenue={b['revenue']:.2f} txn_count={b['txn_count']})"
    )

(REPO_ROOT / "infra" / "seed_schema.sql").write_text("\n".join(lines), encoding="utf-8")

# ---- write tests/golden_fact_sales.example.yaml -------------------------
expected_lines = []
for category in CATEGORIES:
    c = correct[category]
    expected_lines.append(
        f'        - {{product_category: "{category}", revenue: {c["revenue"]:.2f}, txn_count: {c["txn_count"]}}}'
    )

golden_yaml = f'''suite: "fact_sales_golden"
version: "v1"
connection_env: "SYNAPSE_UAT_CONN_STR"

checks:
  - id: "fact_sales_matches_pivot_table"
    category: "business_logic"
    description: "dbo.fact_sales 按品类汇总的收入和笔数必须与你在pivot table里核对过的数字一致"
    severity: "blocker"
    type: "golden_rows"
    params:
      sql: "SELECT product_category, revenue, txn_count FROM dbo.fact_sales"
      key_columns: ["product_category"]
      measures:
        revenue: {{tolerance_abs: 1}}
        txn_count: {{tolerance_abs: 0}}
      expected:
        # Computed by infra/generate_seed_data.py straight from infra/seed_schema.sql's
        # {ROW_COUNT} generated rows -- not hand-picked. Regenerate both together.
{chr(10).join(expected_lines)}
'''

(REPO_ROOT / "tests" / "golden_fact_sales.example.yaml").write_text(golden_yaml, encoding="utf-8")

print("Wrote infra/seed_schema.sql and tests/golden_fact_sales.example.yaml")
print()
print("Correct (golden) totals:")
for category in CATEGORIES:
    c = correct[category]
    b = buggy[category]
    mismatch = " <-- MISMATCH under the buggy procedure" if (c["revenue"], c["txn_count"]) != (b["revenue"], b["txn_count"]) else ""
    print(f"  {category:12s} correct: revenue={c['revenue']:>10.2f} txn_count={c['txn_count']:>4d}   buggy: revenue={b['revenue']:>10.2f} txn_count={b['txn_count']:>4d}{mismatch}")
